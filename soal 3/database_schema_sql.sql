-- Salin dan jalankan skrip SQL ini di SQL Editor dashboard Supabase Anda.

-- 1. Tabel Utama Voucher Kas Keluar (Header)
CREATE TABLE IF NOT EXISTS vouchers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_type VARCHAR(50) NOT NULL DEFAULT 'CASH_OUTFLOW',
    transaction_date DATE NOT NULL,
    reference_no VARCHAR(100) NOT NULL UNIQUE,
    paid_to VARCHAR(255),
    description TEXT NOT NULL,
    total_debit NUMERIC(15, 2) NOT NULL DEFAULT 0,
    total_credit NUMERIC(15, 2) NOT NULL DEFAULT 0,
    currency VARCHAR(10) NOT NULL DEFAULT 'IDR',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Tabel Rincian Baris Jurnal (Journal Entries)
CREATE TABLE IF NOT EXISTS journal_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_id BIGINT REFERENCES vouchers(id) ON DELETE CASCADE,
    line_number INT NOT NULL,
    account_code VARCHAR(50) NOT NULL,
    account_name VARCHAR(150) NOT NULL,
    account_category VARCHAR(100),
    memo TEXT,
    debit NUMERIC(15, 2) NOT NULL DEFAULT 0,
    credit NUMERIC(15, 2) NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Indexing untuk mempercepat pencarian transaksi
CREATE INDEX IF NOT EXISTS idx_vouchers_ref_no ON vouchers(reference_no);
CREATE INDEX IF NOT EXISTS idx_vouchers_date ON vouchers(transaction_date);
CREATE INDEX IF NOT EXISTS idx_journal_voucher_id ON journal_entries(voucher_id);

-- Aktifkan Row Level Security (RLS) untuk akses publik/anonim
ALTER TABLE vouchers ENABLE ROW LEVEL SECURITY;
ALTER TABLE journal_entries ENABLE ROW LEVEL SECURITY;

-- Kebijakan Akses (Policy) untuk Anonymous Insert & Read
CREATE POLICY "Izinkan insert anonim ke vouchers" 
ON vouchers FOR INSERT WITH CHECK (true);

CREATE POLICY "Izinkan select anonim ke vouchers" 
ON vouchers FOR SELECT USING (true);

CREATE POLICY "Izinkan insert anonim ke journal_entries" 
ON journal_entries FOR INSERT WITH CHECK (true);

CREATE POLICY "Izinkan select anonim ke journal_entries" 
ON journal_entries FOR SELECT USING (true);
